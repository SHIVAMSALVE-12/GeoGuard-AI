from dataclasses import dataclass, field


@dataclass
class ReasoningResult:
    """
    Structured output generated by Gemma 3.
    """

    # -------------------------------------------------
    # Disaster Summary
    # -------------------------------------------------

    summary: str = ""

    # -------------------------------------------------
    # Situation Analysis
    # -------------------------------------------------

    analysis: str = ""

    # -------------------------------------------------
    # Overall Severity
    # -------------------------------------------------

    severity: str = "Unknown"

    # -------------------------------------------------
    # Estimated Impact
    # -------------------------------------------------

    impact: str = "Unknown"

    # -------------------------------------------------
    # Confidence
    # -------------------------------------------------

    confidence: float = 0.0

    # -------------------------------------------------
    # Recommendations
    # -------------------------------------------------

    recommendations: list[str] = field(
        default_factory=list
    )

    # -------------------------------------------------
    # Emergency Priority
    # -------------------------------------------------

    priority: str = "Unknown"